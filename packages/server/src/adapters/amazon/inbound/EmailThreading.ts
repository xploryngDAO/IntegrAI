import { AMAZON_ORDER_ID_REGEX, stripAmazonEmailFooter, stripQuotedReply } from '@sac/shared';
import { MAX_PERSISTED_TEXT_CHARS, uniqueStrings } from '../guards';
import type { AmazonAccountSettings, OrderIdSource, SystemSenderKind } from '../types';

/**
 * Pure inbound-e-mail helpers: order id extraction, Amazon sender classification,
 * message-id threading and body normalization. No I/O — unit tested directly.
 */

const EMAIL_ADDRESS_REGEX = /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i;
const BRACKETED_ADDRESS_REGEX = /<([^<>\s]+@[^<>\s]+)>/;
const AMAZON_DOMAIN_REGEX = /(^|\.)amazon\.[a-z.]+$/i;
const ANONYMIZED_BUYER_DOMAIN_REGEX = /(^|\.)marketplace\.amazon\.[a-z.]+$/i;
const SELLER_CENTRAL_LINK_REGEX =
  /https?:\/\/(?:[a-z0-9-]+\.)*sellercentral\.amazon\.[a-z.]+(?:\/[^\s<>"')\]]*)?/gi;

/**
 * Known Amazon system senders. Their e-mails are notifications generated by the
 * relay, never buyer messages: they must not create tickets.
 */
const SYSTEM_SENDER_KINDS: Record<string, SystemSenderKind> = {
  'do-not-reply@amazon.com': 'notification',
  'no-reply@amazon.com.br': 'notification',
  'shipment-tracking@amazon.com': 'tracking',
  'marketplace-messages@amazon.com': 'notification',
};

export interface OrderIdCandidates {
  header?: string | null;
  subject?: string | null;
  body?: string | null;
}

/** Extracts the first Amazon order id (`123-4567890-1234567`) from free text. */
export function extractOrderIdFromText(text: string | null | undefined): string | null {
  if (!text) return null;
  const match = AMAZON_ORDER_ID_REGEX.exec(text);
  return match ? match[0] : null;
}

/** Order id lookup order mandated by the contract: header -> subject -> body. */
export function locateOrderId(candidates: OrderIdCandidates): {
  orderId: string | null;
  source: OrderIdSource | null;
} {
  const header = extractOrderIdFromText(candidates.header);
  if (header) return { orderId: header, source: 'header' };
  const subject = extractOrderIdFromText(candidates.subject);
  if (subject) return { orderId: subject, source: 'subject' };
  const body = extractOrderIdFromText(candidates.body);
  if (body) return { orderId: body, source: 'body' };
  return { orderId: null, source: null };
}

export function extractOrderId(candidates: OrderIdCandidates): string | null {
  return locateOrderId(candidates).orderId;
}

/** Lowercased bare e-mail address (`Name <A@B.com>` -> `a@b.com`). */
export function normalizeEmailAddress(value: string | null | undefined): string | null {
  if (!value) return null;
  const trimmed = value.trim();
  if (trimmed.length === 0) return null;
  const bracketed = BRACKETED_ADDRESS_REGEX.exec(trimmed);
  const candidate = bracketed ? bracketed[1] : (EMAIL_ADDRESS_REGEX.exec(trimmed)?.[0] ?? null);
  if (!candidate) return null;
  return candidate.replace(/^mailto:/i, '').toLowerCase().slice(0, 320);
}

export function domainOfAddress(address: string | null | undefined): string | null {
  const email = normalizeEmailAddress(address);
  if (!email) return null;
  const parts = email.split('@');
  return parts.length === 2 && parts[1]?.length > 0 ? parts[1] : null;
}

function hostMatchesDomain(host: string, domain: string): boolean {
  return host === domain || host.endsWith(`.${domain}`);
}

export function isAmazonAddress(address: string | null | undefined): boolean {
  const domain = domainOfAddress(address);
  return domain !== null && AMAZON_DOMAIN_REGEX.test(domain);
}

/** Amazon anonymizes buyer addresses as `abc123@marketplace.amazon.com.br`. */
export function isAnonymizedAmazonBuyerEmail(address: string | null | undefined): boolean {
  const domain = domainOfAddress(address);
  return domain !== null && ANONYMIZED_BUYER_DOMAIN_REGEX.test(domain);
}

/** Classifies an Amazon relay sender. Returns `null` for buyer messages. */
export function detectSystemSender(address: string | null | undefined): SystemSenderKind | null {
  const email = normalizeEmailAddress(address);
  if (!email) return null;
  const local = email.split('@')[0] ?? '';
  if (local.includes('bounce') || email.includes('bounce')) return 'bounce';
  if (local.includes('blocked') || email.includes('blocked')) return 'blocked';
  const known = SYSTEM_SENDER_KINDS[email];
  return known ?? null;
}

/**
 * External seller-central reply: the `From` is the account's approved SMTP
 * sender (or one of its approved domains) and it is not the buyer.
 */
export function isApprovedSellerSender(
  fromAddress: string | null | undefined,
  settings: AmazonAccountSettings,
  buyerAnonymizedEmail?: string | null,
): boolean {
  const email = normalizeEmailAddress(fromAddress);
  if (!email) return false;
  const buyer = normalizeEmailAddress(buyerAnonymizedEmail);
  if (buyer !== null && email === buyer) return false;
  if (settings.smtpSenderEmail !== null && email === settings.smtpSenderEmail) return true;
  const domain = domainOfAddress(email);
  if (!domain) return false;
  return settings.approvedSenderDomains.some((approved) => hostMatchesDomain(domain, approved));
}

/** Matches the relay recipient against `channel_config.inbound_email_route`. */
export function matchesInboundRoute(
  address: string | null | undefined,
  routes: readonly string[],
): boolean {
  const email = normalizeEmailAddress(address);
  if (!email) return false;
  const domain = domainOfAddress(email);
  return routes.some((route) => {
    const normalizedRoute = route.trim().toLowerCase();
    if (normalizedRoute.length === 0) return false;
    if (normalizedRoute === email) return true;
    if (!domain) return false;
    const bare = normalizedRoute.replace(/^@/, '');
    if (bare.length === 0) return false;
    return normalizedRoute === `@${domain}` || bare === domain || domain.endsWith(`.${bare}`);
  });
}

/** Strips `<...>` from a Message-ID / In-Reply-To value. */
export function normalizeMessageId(value: string | null | undefined): string | null {
  const trimmed = value?.trim();
  if (!trimmed) return null;
  const bracketed = /<([^<>]+)>/.exec(trimmed);
  const candidate = (bracketed ? bracketed[1] : (trimmed.split(/\s+/)[0] ?? '')).replace(/[;,]+$/, '').trim();
  if (candidate.length === 0) return null;
  return candidate.slice(0, 400);
}

/** `References` header -> ordered de-duplicated message ids. */
export function splitReferences(value: string | string[] | null | undefined): string[] {
  const raw = Array.isArray(value) ? value.join(' ') : (value ?? '');
  const ids: string[] = [];
  for (const token of raw.split(/\s+/)) {
    const id = normalizeMessageId(token);
    if (id && !ids.includes(id)) ids.push(id);
  }
  return ids.slice(0, 50);
}

export function truncateText(text: string, maxChars = MAX_PERSISTED_TEXT_CHARS): string {
  return text.length > maxChars ? text.slice(0, maxChars) : text;
}

/**
 * Amazon footer + quoted history removal, newline/whitespace normalization.
 * Used for `bodyCleanText` and for order-id / link / opt-out detection.
 */
export function normalizeBodyText(raw: string): string {
  if (!raw) return '';
  let text = raw.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  text = stripAmazonEmailFooter(text);
  text = stripQuotedReply(text);
  text = text
    .split('\n')
    .map((line) => line.replace(/[ \t]+/g, ' ').trimEnd())
    .join('\n');
  text = text.replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '').trim();
  return truncateText(text);
}

/** Finds the Seller Central "no response needed" link inside a relayed e-mail. */
export function extractSellerCentralLink(
  ...sources: Array<string | null | undefined>
): string | null {
  for (const source of sources) {
    if (!source) continue;
    const match = source.match(SELLER_CENTRAL_LINK_REGEX);
    if (match && match.length > 0) {
      const link = match[0].replace(/[.,;:!?)\]]+$/, '');
      return link.length > 0 ? link : null;
    }
  }
  return null;
}

/** Trims and de-duplicates approved link domains (lowercase). */
export function normalizeDomainList(domains: readonly string[]): string[] {
  return uniqueStrings(domains.map((domain) => domain.trim().toLowerCase()).filter((domain) => domain.length > 0));
}
